const F_BLOCK = new Set(["lanthanide", "actinide"]);

export const ELEMENTS_TABLE = RAW.map(([z, symbol, name, group, period, category, fact]) => {
  const isFBlock = F_BLOCK.has(category);
  const blockIndex = isFBlock ? z - (period === 6 ? 57 : 89) : -1;
  return {
    z,
    symbol,
    name,
    group,
    period,
    category,
    fact: fact || null,
    col: isFBlock ? 3 + blockIndex : group,
    row: isFBlock ? (period === 6 ? 9 : 10) : period,
  };
});

export const getElementBySymbol = (symbol) =>
  ELEMENTS_TABLE.find((element) => element.symbol === symbol);

